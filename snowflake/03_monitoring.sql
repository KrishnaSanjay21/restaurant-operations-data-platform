USE DATABASE RESTAURANT_OPS;

CREATE OR REPLACE VIEW ANALYTICS.VW_PIPELINE_FRESHNESS AS
SELECT 'INSPECTIONS' AS SOURCE_NAME, MAX(_LOADED_AT) AS LAST_LOADED_AT,
       DATEDIFF('hour', MAX(_LOADED_AT), CURRENT_TIMESTAMP()) AS HOURS_SINCE_LOAD
FROM RAW.INSPECTIONS
UNION ALL
SELECT 'COMPLAINTS', MAX(_LOADED_AT), DATEDIFF('hour', MAX(_LOADED_AT), CURRENT_TIMESTAMP())
FROM RAW.COMPLAINTS
UNION ALL
SELECT 'WEATHER', MAX(_LOADED_AT), DATEDIFF('hour', MAX(_LOADED_AT), CURRENT_TIMESTAMP())
FROM RAW.WEATHER;

CREATE OR REPLACE VIEW ANALYTICS.VW_LOAD_RECONCILIATION AS
SELECT
    BATCH_ID,
    SOURCE_NAME,
    SOURCE_COUNT,
    LOADED_COUNT,
    REJECTED_COUNT,
    SOURCE_COUNT - LOADED_COUNT - REJECTED_COUNT AS RECONCILIATION_VARIANCE,
    STATUS,
    ERROR_MESSAGE,
    COMPLETED_AT
FROM RAW.LOAD_AUDIT;

