-- Run as a Snowflake account administrator. Replace role ownership if your
-- organization uses a different governance model.

CREATE ROLE IF NOT EXISTS RESTAURANT_OPS_LOADER;
CREATE ROLE IF NOT EXISTS RESTAURANT_OPS_TRANSFORMER;
CREATE ROLE IF NOT EXISTS RESTAURANT_OPS_REPORTER;

CREATE WAREHOUSE IF NOT EXISTS RESTAURANT_OPS_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS RESTAURANT_OPS;
CREATE SCHEMA IF NOT EXISTS RESTAURANT_OPS.RAW;
CREATE SCHEMA IF NOT EXISTS RESTAURANT_OPS.ANALYTICS;

GRANT USAGE ON WAREHOUSE RESTAURANT_OPS_WH TO ROLE RESTAURANT_OPS_LOADER;
GRANT USAGE ON WAREHOUSE RESTAURANT_OPS_WH TO ROLE RESTAURANT_OPS_TRANSFORMER;
GRANT USAGE ON WAREHOUSE RESTAURANT_OPS_WH TO ROLE RESTAURANT_OPS_REPORTER;
GRANT USAGE ON DATABASE RESTAURANT_OPS TO ROLE RESTAURANT_OPS_LOADER;
GRANT USAGE ON DATABASE RESTAURANT_OPS TO ROLE RESTAURANT_OPS_TRANSFORMER;
GRANT USAGE ON DATABASE RESTAURANT_OPS TO ROLE RESTAURANT_OPS_REPORTER;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT, CREATE PROCEDURE
    ON SCHEMA RESTAURANT_OPS.RAW TO ROLE RESTAURANT_OPS_LOADER;
GRANT USAGE, CREATE TABLE, CREATE VIEW
    ON SCHEMA RESTAURANT_OPS.ANALYTICS TO ROLE RESTAURANT_OPS_TRANSFORMER;
GRANT USAGE ON SCHEMA RESTAURANT_OPS.ANALYTICS TO ROLE RESTAURANT_OPS_REPORTER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RESTAURANT_OPS.ANALYTICS TO ROLE RESTAURANT_OPS_REPORTER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA RESTAURANT_OPS.ANALYTICS TO ROLE RESTAURANT_OPS_REPORTER;

USE DATABASE RESTAURANT_OPS;
USE SCHEMA RAW;

CREATE FILE FORMAT IF NOT EXISTS PARQUET_FORMAT
    TYPE = PARQUET
    USE_LOGICAL_TYPE = TRUE
    REPLACE_INVALID_CHARACTERS = TRUE;

