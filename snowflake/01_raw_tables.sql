USE DATABASE RESTAURANT_OPS;
USE SCHEMA RAW;

CREATE TABLE IF NOT EXISTS INSPECTIONS (
    SOURCE_ROW_KEY STRING,
    INSPECTION_KEY STRING,
    VIOLATION_KEY STRING,
    RESTAURANT_ID STRING,
    RESTAURANT_NAME STRING,
    BOROUGH STRING,
    BUILDING STRING,
    STREET STRING,
    ADDRESS_NORMALIZED STRING,
    ZIPCODE STRING,
    PHONE STRING,
    CUISINE_DESCRIPTION STRING,
    INSPECTION_DATE TIMESTAMP_TZ,
    ACTION STRING,
    VIOLATION_CODE STRING,
    VIOLATION_DESCRIPTION STRING,
    CRITICAL_FLAG STRING,
    SCORE FLOAT,
    GRADE STRING,
    GRADE_DATE TIMESTAMP_TZ,
    RECORD_DATE TIMESTAMP_TZ,
    INSPECTION_TYPE STRING,
    LATITUDE FLOAT,
    LONGITUDE FLOAT,
    LOCATION_KEY STRING,
    _BATCH_ID STRING,
    _RETRIEVED_AT TIMESTAMP_TZ,
    _LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS COMPLAINTS (
    COMPLAINT_ID STRING,
    CREATED_DATE TIMESTAMP_TZ,
    CLOSED_DATE TIMESTAMP_TZ,
    AGENCY STRING,
    AGENCY_NAME STRING,
    COMPLAINT_TYPE STRING,
    DESCRIPTOR STRING,
    LOCATION_TYPE STRING,
    INCIDENT_ZIP STRING,
    INCIDENT_ADDRESS STRING,
    ADDRESS_NORMALIZED STRING,
    STREET_NAME STRING,
    CITY STRING,
    STATUS STRING,
    RESOLUTION_DESCRIPTION STRING,
    BOROUGH STRING,
    LATITUDE FLOAT,
    LONGITUDE FLOAT,
    OPEN_DATA_CHANNEL_TYPE STRING,
    LOCATION_KEY STRING,
    _BATCH_ID STRING,
    _RETRIEVED_AT TIMESTAMP_TZ,
    _LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS WEATHER (
    WEATHER_KEY STRING,
    STATION_ID STRING,
    WEATHER_DATE DATE,
    TEMPERATURE_MAX_F FLOAT,
    TEMPERATURE_MIN_F FLOAT,
    PRECIPITATION_IN FLOAT,
    SNOWFALL_IN FLOAT,
    SNOW_DEPTH_IN FLOAT,
    AVERAGE_WIND_MPH FLOAT,
    _BATCH_ID STRING,
    _RETRIEVED_AT TIMESTAMP_TZ,
    _LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS LOAD_AUDIT (
    BATCH_ID STRING,
    SOURCE_NAME STRING,
    STARTED_AT TIMESTAMP_TZ,
    COMPLETED_AT TIMESTAMP_TZ,
    SOURCE_COUNT NUMBER,
    LOADED_COUNT NUMBER,
    REJECTED_COUNT NUMBER,
    STATUS STRING,
    ERROR_MESSAGE STRING
);

